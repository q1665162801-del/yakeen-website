import zipfile, re

p = r'd:\trae work\工作空间\6a9fff36e331b99419567482\Yakeen_网站优化完成报告_p11.docx'
bad = re.compile(r'python|trae|skill|ponytail|generated by|openai|anthropic|claude|codex', re.I)
with zipfile.ZipFile(p) as z:
    for n in z.namelist():
        data = z.read(n)
        try:
            txt = data.decode('utf-8')
        except Exception:
            continue
        for m in bad.finditer(txt):
            s = max(0, m.start() - 60)
            print(n, '->', txt[s:m.end() + 60].replace('\n', ' '))
print('scan done')
